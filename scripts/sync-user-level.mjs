import { spawnSync } from 'child_process'
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'fs'
import os from 'os'
import path from 'path'
import { fileURLToPath } from 'url'

// Installs the plugins of this marketplace as user-level commands and agents in
// ~/.claude, for environments where the /plugin command is unavailable (e.g. the
// VS Code extension build). The marketplace stays the source of truth: edit the
// plugin, then re-run this script.
//
// Usage: node scripts/sync-user-level.mjs [--dry-run]

const dryRun = process.argv.includes('--dry-run')
const marketplaceRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
)
const claudeHome = path.join(os.homedir(), '.claude')

const manifestPath = path.join(
  marketplaceRoot,
  '.claude-plugin',
  'marketplace.json',
)
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))

const GENERATED_MARK = 'generated by scripts/sync-user-level.mjs'

const write = (target, content) => {
  if (dryRun) {
    console.log(`would write ${target}`)
    return
  }
  mkdirSync(path.dirname(target), { recursive: true })
  writeFileSync(target, content)
  console.log(`wrote ${target}`)
}

// Only ever delete files this script generated, so a hand-written user command
// is never clobbered by a stale plugin sync.
const pruneGenerated = (dir, keep) => {
  if (!existsSync(dir)) return
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.md')) continue
    const file = path.join(dir, entry.name)
    if (keep.has(file)) continue
    if (!readFileSync(file, 'utf8').includes(GENERATED_MARK)) continue
    if (dryRun) {
      console.log(`would remove stale ${file}`)
      continue
    }
    rmSync(file)
    console.log(`removed stale ${file}`)
  }
}

const stamp = source =>
  `\n<!-- ${GENERATED_MARK} from ${source.split(path.sep).join('/')} — edit there, not here -->\n`

const generatedCommands = new Set()
const generatedAgents = new Set()

for (const entry of manifest.plugins) {
  const pluginRoot = path.resolve(marketplaceRoot, entry.source)
  const pluginRootPosix = pluginRoot.split(path.sep).join('/')
  console.log(`\n# ${entry.name} (${pluginRootPosix})`)

  // commands/<file>.md -> ~/.claude/commands/<plugin>/<file>.md, so the command
  // keeps the same /<plugin>:<file> name it has when installed as a plugin.
  const commandsDir = path.join(pluginRoot, 'commands')
  if (existsSync(commandsDir)) {
    for (const file of readdirSync(commandsDir)) {
      if (!file.endsWith('.md')) continue
      const source = path.join(commandsDir, file)
      // CLAUDE_PLUGIN_ROOT only exists for real plugin installs.
      const body = readFileSync(source, 'utf8')
        .replaceAll('${CLAUDE_PLUGIN_ROOT}', pluginRootPosix)
        .replaceAll('$CLAUDE_PLUGIN_ROOT', pluginRootPosix)
      const target = path.join(claudeHome, 'commands', entry.name, file)
      generatedCommands.add(target)
      write(target, body + stamp(source))
    }
  }

  // Agent names are global, so they land directly in ~/.claude/agents.
  const agentsDir = path.join(pluginRoot, 'agents')
  if (existsSync(agentsDir)) {
    for (const file of readdirSync(agentsDir)) {
      if (!file.endsWith('.md')) continue
      const source = path.join(agentsDir, file)
      const target = path.join(claudeHome, 'agents', file)
      generatedAgents.add(target)
      write(target, readFileSync(source, 'utf8') + stamp(source))
    }
  }

  // Skills keep their own directory layout.
  const skillsDir = path.join(pluginRoot, 'skills')
  if (existsSync(skillsDir)) {
    for (const skill of readdirSync(skillsDir, { withFileTypes: true })) {
      if (!skill.isDirectory()) continue
      const source = path.join(skillsDir, skill.name, 'SKILL.md')
      if (!existsSync(source)) continue
      const target = path.join(claudeHome, 'skills', skill.name, 'SKILL.md')
      if (dryRun) {
        console.log(`would copy ${source} -> ${target}`)
      } else {
        mkdirSync(path.dirname(target), { recursive: true })
        copyFileSync(source, target)
        console.log(`copied ${target}`)
      }
    }
  }
}

for (const dir of new Set(
  [...generatedCommands].map(file => path.dirname(file)),
)) {
  pruneGenerated(dir, generatedCommands)
}
pruneGenerated(path.join(claudeHome, 'agents'), generatedAgents)

const head = spawnSync('git', ['rev-parse', '--short', 'HEAD'], {
  cwd: marketplaceRoot,
  encoding: 'utf8',
})
console.log(
  `\nsynced from ${marketplaceRoot} @ ${head.status === 0 ? head.stdout.trim() : 'unknown'}${dryRun ? ' (dry run)' : ''}`,
)
console.log('Reload the Claude Code window to pick up new commands and agents.')
